CROP_PAD = 12                      # 目标裁剪外扩像素
# 识别前最长边缩放。必须 >= ocr._MAX_OCR_SIDE(1600)：低于 OCR 内部上限时，
# 小字号包装文字会在检测阶段就丢字（实测红豆奶茶原图 1500px 读出 79 行含
# "食品名称：红豆奶茶"，降到 1280 后只剩 8 行、名称丢失）。设 1600 与 OCR
# 上限对齐：OCR/YOLO/CLIP 精度不损，点阵解码与超大图仍能降采样省算力。
